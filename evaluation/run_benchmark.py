"""Command-Line Interface for Running NOESIS Scientific Benchmark Experiments."""

from __future__ import annotations

import argparse
import sys
from datetime import datetime
from pathlib import Path

# Ensure repository root is in sys.path
ROOT_DIR = str(Path(__file__).resolve().parent.parent)
if ROOT_DIR not in sys.path:
    sys.path.insert(0, ROOT_DIR)

from evaluation.runner import BenchmarkRunner
from evaluation.schemas import ExperimentConfig


def main() -> None:
    parser = argparse.ArgumentParser(description="NOESIS Research Benchmark Evaluation Runner")
    parser.add_argument(
        "--system",
        choices=["noesis", "noesis_no_eaqc", "noesis-no-eaqc", "standard_kg", "standard-kg", "rag"],
        default="noesis",
        help="Target system architecture under evaluation",
    )
    parser.add_argument(
        "--corpus",
        default="SYNTHETIC-CORPUS-V2",
        help="Identifier of target corpus",
    )
    parser.add_argument(
        "--category",
        default="all",
        help="Filter specific benchmark category or 'all'",
    )
    parser.add_argument(
        "--mode",
        choices=["structured", "natural"],
        default="structured",
        help="Evaluation mode: Oracle Graph Execution ('structured') or Natural-Language Query Compilation ('natural')",
    )
    parser.add_argument(
        "--split",
        choices=["dev", "test", "all"],
        default="all",
        help="Partition split to evaluate on: 'dev', 'test', or 'all'",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Optional ceiling limit on the number of cases to evaluate",
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Resume prior interrupted experiment run using --experiment-id",
    )
    parser.add_argument(
        "--experiment-id",
        type=str,
        default=None,
        help="Unique experiment identifier (defaults to autogenerated timestamped id)",
    )
    parser.add_argument(
        "--cache-policy",
        choices=["use_cache", "clear_cache"],
        default="use_cache",
        help="Query plan cache policy",
    )

    args = parser.parse_args()

    # Generate default experiment ID if not supplied
    if not args.experiment_id:
        timestamp_str = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
        sys_tag = args.system.replace("-", "_")
        exp_id = f"exp_{sys_tag}_{args.mode}_{args.split}_{timestamp_str}"
    else:
        exp_id = args.experiment_id

    # Normalize system name
    norm_sys = args.system.replace("-", "_")

    config = ExperimentConfig(
        experiment_id=exp_id,
        system_name=norm_sys,
        mode=args.mode,
        corpus_id=args.corpus,
        split=args.split,
        category=args.category,
        limit=args.limit,
        resume=args.resume,
        cache_policy=args.cache_policy,
    )

    runner = BenchmarkRunner(config)
    summary = runner.run()

    print("\n" + "=" * 70)
    print(f"EXPERIMENT SUMMARY: {summary.experiment_id}")
    print("=" * 70)
    print(f"System:            {summary.config.system_name}")
    print(f"Mode:              {summary.config.mode}")
    print(f"Split:             {summary.config.split}")
    print(f"Total Cases:       {summary.total_cases}")
    print(f"Completed Cases:   {summary.completed_cases}")
    print(f"Failed Cases:      {summary.failed_cases}")
    print(f"Duration:          {summary.duration_seconds}s")
    print("-" * 70)
    print(f"{'Metric Name':<35} {'Value':<10} {'Details'}")
    print("-" * 70)

    for mname, mdata in summary.metrics.items():
        val = mdata.get("value", 0.0)
        num = mdata.get("numerator", 0.0)
        den = mdata.get("denominator", 0.0)
        details = f"({num:.1f}/{den:.1f})" if den > 0 else f"(n={mdata.get('sample_size', 0)})"
        print(f"{mname:<35} {val:<10.4f} {details}")

    print("=" * 70)
    print(f"Artifacts saved to: {runner.output_dir}\n")


if __name__ == "__main__":
    main()
