"""Base LLM Provider Interface and Data Models."""

from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, ConfigDict, Field


class LLMResponse(BaseModel):
    """Normalized response payload from any LLM provider with comprehensive telemetry."""

    model_config = ConfigDict(protected_namespaces=())

    content: str = Field(..., description="Raw text or JSON string generated by the model")
    model: str = Field(..., description="Identifier of the model that executed inference")
    inference_duration_ms: float = Field(..., description="Wall-clock HTTP inference duration in milliseconds")
    prompt_tokens: Optional[int] = Field(default=None, description="Input token count if reported")
    completion_tokens: Optional[int] = Field(default=None, description="Output token count if reported")
    total_duration_ms: Optional[float] = Field(default=None, description="Ollama server total duration in ms")
    load_duration_ms: Optional[float] = Field(default=None, description="Model loading duration in ms")
    prompt_eval_duration_ms: Optional[float] = Field(default=None, description="Prompt evaluation duration in ms")
    eval_duration_ms: Optional[float] = Field(default=None, description="Token generation duration in ms")
    done_reason: Optional[str] = Field(default=None, description="Reason generation finished ('stop', 'length')")
    is_cold_start: bool = Field(default=False, description="Whether this request incurred model load overhead")
    raw_response: Optional[Dict[str, Any]] = Field(default=None, description="Original raw provider response")

    @property
    def text(self) -> str:
        """Alias for content."""
        return self.content


class LLMStatus(BaseModel):
    """Telemetry report describing provider and model readiness."""

    model_config = ConfigDict(protected_namespaces=())

    available: bool = Field(..., description="Whether the local LLM service is reachable")
    provider_name: str = Field(..., description="Name of the provider implementation (e.g. 'ollama')")
    base_url: str = Field(..., description="Base endpoint URL of the local provider")
    configured_model: str = Field(..., description="Target model name configured in settings")
    installed_models: List[str] = Field(default_factory=list, description="List of local models discovered")
    model_available: bool = Field(..., description="Whether the configured target model is installed locally")
    details: Optional[str] = Field(default=None, description="Diagnostic message or connectivity details")

    def to_dict(self) -> Dict[str, Any]:
        """Serializes status model to dictionary."""
        return self.model_dump()


class LLMUnavailableError(Exception):
    """Raised when the local LLM daemon is offline or unreachable."""

    pass


class LLMInferenceError(Exception):
    """Raised when the LLM returns an error or malformed payload."""

    pass


class BaseLLMProvider(ABC):
    """Abstract interface defining local LLM interactions."""

    @abstractmethod
    def check_status(self) -> LLMStatus:
        """Probes the local daemon and reports connectivity and model presence."""
        pass

    @abstractmethod
    def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        schema: Optional[Any] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
        context_length: Optional[int] = None,
    ) -> LLMResponse:
        """Executes a single-turn prompt inference and returns a validated LLMResponse."""
        pass

    def is_available(self) -> bool:
        """Returns True if the provider is reachable and configured model is installed."""
        try:
            status = self.check_status()
            return bool(status.available and status.model_available)
        except Exception:
            return False

    @property
    def model_name(self) -> str:
        """Returns the configured model name."""
        return self.check_status().configured_model
